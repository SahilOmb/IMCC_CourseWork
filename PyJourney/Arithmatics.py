x = 10
y = 3

print(x + y)   # 13  -> Addition
print(x - y)   # 7   -> Subtraction
print(x * y)   # 30  -> Multiplication
print(x / y)   # 3.3333... -> Float Division (always returns a decimal)
print(x // y)  # 3   -> Floor Division (drops the decimal, rounds down)
print(x % y)   # 1   -> Modulus (returns the remainder of the division)
print(x ** y)  # 1000 -> Exponentiation (10 to the power of 3)


