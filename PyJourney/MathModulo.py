import math

# Roots and Powers
print(math.sqrt(16))      # 4.0  -> Square root
print(math.pow(2, 3))     # 8.0  -> 2 raised to the power of 3 (returns float)

# Precise Rounding
print(math.ceil(4.1))     # 5    -> Ceil (always rounds UP to next integer)
print(math.floor(4.9))    # 4    -> Floor (always rounds DOWN to next integer)

# Absolute Value
print(math.fabs(-10.5))   # 10.5 -> Absolute value (removes negative sign)

# Built-in Constants
print(math.pi)            # 3.141592653589793
print(math.e)             # 2.718281828459045
